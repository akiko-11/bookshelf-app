<?php

namespace Database\Seeders;

use App\Models\Book;
use App\Models\Review;
use App\Models\User;
use Illuminate\Database\Seeder;

class ReviewSeeder extends Seeder
{
    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        $users = User::all();
        $books = Book::all();

        // 評価別のコメントテンプレート
        $comments = [
            5 => [
                '素晴らしい本でした！',
                '人生が変わりました。',
                '何度も読み返しています。',
            ],
            4 => [
                'とても参考になりました。',
                '読みやすくておすすめです。',
                '期待通りの内容でした。',
            ],
            3 => [
                '普通でした。',
                '可もなく不可もなく。',
                '期待したほどではなかった。',
            ],
            2 => [
                '少し期待外れでした。',
                '内容が薄い印象。',
                'もう少し深掘りしてほしかった。',
            ],
            1 => [
                '残念ながら合いませんでした。',
                '期待と違いました。',
            ],
        ];

        foreach ($books as $book) {
            // 1冊につき2〜4件のレビューを生成
            $reviewCount = rand(2, 4);

            // 重複しない投稿ユーザーをランダムに選択
            $reviewUsers = $users->random($reviewCount);

            foreach ($reviewUsers as $user) {
                // 評価を1〜5から選択
                $rating = rand(1, 5);

                // 評価に対応するコメントをランダムに選択
                $comment = $comments[$rating][array_rand($comments[$rating])];

                Review::create([
                    'user_id' => $user->id,
                    'book_id' => $book->id,
                    'rating' => $rating,
                    'comment' => $comment,
                ]);
            }
        }
    }
}
